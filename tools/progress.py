#!/usr/bin/env python3
"""Regenerates docs/progress.md from every file in tools/results/ (jqcompat records and timing files).
usage: python tools/progress.py [--results tools/results] [--md docs/progress.md]
Add a stage: see the header of docs/progress.md."""
import argparse, glob, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from jqcompat import load_tags  # tag order comes from the matrix

HEADER = """# Progress by stage

Generated by `tools/progress.py` from the JSON files in `tools/results/`. Do not edit by hand.

What is measured: jq 1.8.2's own `tests/jq.test` (531 runnable cases plus 19 `%%FAIL` cases that must not compile), run through every tool the same way:
the program is the argument (jx) or read from a file (jq, jaq), the input is on standard input, output is compared with `-c` as parsed JSON.
`tools/jqcompat.py` documents the harness; `docs/jq-feature-matrix.md` explains the feature tags. Classes:

- **pass**: output equals jq's expected output (parsed JSON, so key order and number text may differ); the table also counts byte-identical passes.
- **differ**: the tool accepted the program and ran, but the output is wrong.
- **rejected**: the tool refused the program up front (jx: exit 1 with "not supported" or a syntax error, exit 2 for an unknown option; jaq: does not compile). Honest non-support, not a failure.
- **error**: crash, timeout, or an unexpected run-time error on a case that should succeed.

jx stops early on some filters and does not validate an unread tail (documented in the README); that only counts as `differ` when the printed output is wrong.
Cases whose input is not one strict JSON document (NaN, duplicate keys, several top-level values) that end as differ or error are counted as documented differences (the `expected diffs` column).

## Add a new stage

```
./build.sh D:/tmp/w/jxprog-build/jxN.exe          # needs the Mitochondria compiler, see README.md
python -I tools/jqcompat.py record --test D:/tmp/w/jqcompat/jq.test --jx D:/tmp/w/jxprog-build/jxN.exe --label stageN --jx-repo .
python -I tools/timing.py --jx D:/tmp/w/jxprog-build/jxN.exe --label stageN --jx-repo .
python tools/progress.py
```

`--jx-repo` is the checkout the exe was built from (its commit is recorded). `jq.test` is jq-1.8.2's `tests/jq.test`. jq and jaq are
re-recorded only when their versions change: `python -I tools/jqcompat.py record --test jq.test --tool jq` (or `--tool jaq`; `--modules DIR` for the module cases).
"""


def stage_key(r):
    m = re.search(r"(\d+)", r["label"])
    return (0 if r["tool"] == "jq" else 1 if r["tool"] == "jaq" else 2, int(m.group(1)) if m else 0, r["date"], r["label"])


def name(r):
    if r["tool"] == "jx":
        m = re.fullmatch(r"stage(\d+)", r["label"])
        return "jx Stage " + m.group(1) if m else "jx " + r["label"]
    return "%s %s" % (r["tool"], r["version"].split()[-1].replace("jq-", ""))


def pct(a, b):
    return "%.1f%%" % (100.0 * a / b) if b else "-"


def table(head, rows):
    return ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"] + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default=os.path.join(ROOT, "tools", "results"))
    ap.add_argument("--md", default=os.path.join(ROOT, "docs", "progress.md"))
    a = ap.parse_args()
    recs, timings = [], []
    for f in sorted(glob.glob(os.path.join(a.results, "*.json"))):
        d = json.load(open(f, encoding="utf-8"))
        (timings if "timing" in d else recs).append(d)
    recs.sort(key=stage_key)
    jx = [r for r in recs if r["tool"] == "jx"]
    L = [HEADER]

    L.append("## 1. Headline: jq.test results by tool and stage\n")
    rows = []
    for r in recs:
        t = r["totals"]
        n = t["runnable"]
        f = t["fail_cases"]
        rows.append([name(r), n, t["pass"], t["differ"], t["rejected"], t["error"], pct(t["pass"], n), pct(t["pass"], n - t["rejected"]),
                     t["bytes_identical"], t["expected_diffs"], "%d / %d" % (f["pass"], t["cases"] - n)])
    L += table(["tool / stage", "cases", "pass", "differ", "rejected (not supported)", "error", "pass % of all", "pass % of accepted",
                "byte-identical", "expected diffs", "%%FAIL cases passed"], rows)
    L.append("")
    L.append("`cases` are the runnable cases (jq.test has 550 entries; the `%%FAIL` entries appear only in the last column: a pass there means the tool refused the program, "
             "so a stage that rejects everything it does not know trivially passes some of them). The matrix document's 371 of 550 for jaq is 359 + its 12 `%%FAIL` passes.\n")

    L.append("## 2. By feature tag (pass count; the `cases` column is how many runnable cases carry the tag)\n")
    L.append("A case carries several tags, so rows overlap; `core` carries every case. What the tags mean: `docs/jq-feature-matrix.md`.\n")
    ref = next((r for r in recs if r["tool"] == "jq"), recs[0])
    order = [t["tag"] for t in load_tags() if t["tag"] in ref["tags"]]
    order.sort(key=lambda t: -ref["tags"][t]["total"])
    head = ["tag", "cases"] + [name(r) for r in recs]
    rows = []
    for t in order:
        rows.append([t, ref["tags"][t]["total"]] + ["%d" % r["tags"].get(t, {}).get("pass", 0) for r in recs])
    L += table(head, rows)
    L.append("")

    L.append("## 3. What changed since the previous stage\n")
    if not jx:
        L.append("No jx stage recorded yet.\n")
    prev = None
    for r in jx:
        L.append("**%s**%s\n" % (name(r), "" if prev else " (first recorded stage; changes are counted from zero)"))
        ups, downs = [], []
        for t in order:
            now = r["tags"].get(t, {}).get("pass", 0)
            before = prev["tags"].get(t, {}).get("pass", 0) if prev else 0
            if now > before:
                ups.append("%s +%d (%d of %d)" % (t, now - before, now, ref["tags"][t]["total"]))
            elif now < before:
                downs.append("%s %d (%d -> %d)" % (t, now - before, before, now))
        newly = lost = 0
        if prev and len(prev["cases"]) == len(r["cases"]):
            for x, y in zip(prev["cases"], r["cases"]):
                newly += (y[0] == "p" and x[0] != "p")
                lost += (x[0] == "p" and y[0] != "p")
        L.append("- tags with more passing cases: " + ("; ".join(ups) if ups else "none"))
        L.append("- tags with fewer passing cases (regressions): " + ("; ".join(downs) if downs else "none"))
        if prev:
            L.append("- cases newly passing: %d; no longer passing: %d" % (newly, lost))
        L.append("")
        prev = r

    L.append("## 4. Runs\n")
    rows = [[name(r), r["date"], r.get("commit") or "-", r["version"] or "-"] for r in recs]
    L += table(["tool / stage", "date", "jx commit", "tool version"], rows)
    L.append("")

    L.append("## 5. Speed (median milliseconds, whole process on Windows, lower is better)\n")
    L.append("Each stage's run times jx, jq and jaq again on the same machine (`tools/timing.py`, which runs `bench/bench.py`); cells are `jx / jq / jaq`. "
             "Documents: `{\"users\":[...]}` with rows of `{n, age, tags, addr}`. jx is built by `./build.sh` (clang -O3 with the larger inlining budget). "
             "A filter a stage rejects shows `n/a` for jx.\n")
    timings.sort(key=lambda d: (int((re.search(r"(\d+)", d["label"]) or [0, 0])[1]), d["date"]))
    if timings:
        sizes = sorted({r["size"] for d in timings for r in d["timing"]}, key=lambda s: float(s.split()[0]))
        filters = []
        for d in timings:
            for r in d["timing"]:
                if r["filter"] not in filters:
                    filters.append(r["filter"])
        for sz in sizes:
            L.append("**%s**\n" % sz)
            rows = []
            for d in timings:
                row = [d["label"], d["date"], d.get("commit") or "-"]
                for flt in filters:
                    m = next((r["ms"] for r in d["timing"] if r["size"] == sz and r["filter"] == flt), None)
                    row.append(" / ".join(m.get(k, "-") for k in ("jx", "jq", "jaq")) if m else "-")
                rows.append(row)
            L += table(["stage", "date", "commit"] + ["`%s`" % f.replace("|", "\\|") for f in filters], rows)
            L.append("")
    else:
        L.append("No timing run recorded yet.\n")
    # peak memory: the same layout as the speed tables, from the files that carry it
    if any("peak" in r for d in timings for r in d["timing"]):
        L.append("## 6. Peak memory (peak working set in MB, whole process, lower is better)\n")
        L.append("Same runs as section 5 (`tools/timing.py`); cells are `jx / jq / jaq`. jq is the real `jq.exe` (the `jq` on PATH is a launcher that hides its memory). "
                 "jx reads the whole input into memory, so the document size is its floor.\n")
        for sz in sizes:
            L.append("**%s**\n" % sz)
            rows = []
            for d in timings:
                if not any("peak" in r for r in d["timing"]):
                    continue
                row = [d["label"], d["date"]]
                for flt in filters:
                    m = next((r.get("peak") for r in d["timing"] if r["size"] == sz and r["filter"] == flt), None)
                    row.append(" / ".join(m.get(k, "-") for k in ("jx", "jq", "jaq")) if m else "-")
                rows.append(row)
            L += table(["stage", "date"] + ["`%s`" % f.replace("|", "\\|") for f in filters], rows)
            L.append("")

    # milestones of the newest stage: one compact table
    if jx:
        top = max(int((re.search(r"stage(\d+)", r["label"]) or [0, 0])[1]) for r in jx)
        ms = [r for r in jx if re.fullmatch(r"stage%d-.+" % top, r["label"])]
        if ms:
            L.append("## 7. Milestones of Stage %d\n" % top)
            L.append("One row per finished feature tag (label `stage%d-<tag>`): jq.test results, then time and peak memory (MB) of the `select` filter on the 16.3 MB document.\n" % top)
            rows = []
            for r in ms:
                t = r["totals"]
                tim = next((d for d in timings if d["label"] == r["label"]), None)
                cell = "-"
                if tim:
                    x = next((q for q in tim["timing"] if q["filter"] == ".users[] | select(.age >= 85) | .n" and q["size"].startswith("16")), None)
                    if x:
                        cell = "%s ms / %s MB" % (x["ms"].get("jx", "-"), x.get("peak", {}).get("jx", "-"))
                rows.append([r["label"], r["date"], r.get("commit") or "-", t["pass"], t["differ"], t["rejected"], t["error"], pct(t["pass"], t["runnable"]), cell])
            L += table(["milestone", "date", "commit", "pass", "differ", "rejected", "error", "pass %", "`select` on 16.3 MB"], rows)
            L.append("")
    open(a.md, "w", encoding="utf-8", newline="\n").write("\n".join(L).rstrip("\n") + "\n")
    print("wrote", a.md, len(L), "blocks")


main()
