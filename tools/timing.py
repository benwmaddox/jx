#!/usr/bin/env python3
"""Runs bench/bench.py for one jx build and stores the median milliseconds as tools/results/DATE-LABEL-timing.json.
usage: python -I tools/timing.py --jx EXE --label stageN [--jx-repo DIR] [--rows 20000,200000] [--data DIR] [--runs N]
The documents (generated by bench.py, 1.59 MB at 20000 rows and 16.3 MB at 200000 rows) go under --data, never into the repo.
Reference tools (jq, jaq) are timed again in every run on the same machine, so each stage's row is comparable on its own."""
import argparse, datetime, json, os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ap = argparse.ArgumentParser()
ap.add_argument("--jx", required=True)
ap.add_argument("--label", required=True)
ap.add_argument("--jx-repo")
ap.add_argument("--rows", default="20000,200000")
ap.add_argument("--data", default=r"D:\tmp\w\jxprog-build\data")
ap.add_argument("--runs", default="15")
ap.add_argument("--date")
ap.add_argument("--results", default=os.path.join(os.path.dirname(HERE), "tools", "results"))
a = ap.parse_args()
env = dict(os.environ, JX=a.jx, DATA=a.data, OLDJX=os.path.join(a.data, "none.exe"))
env.pop("JXI", None)
p = subprocess.run([sys.executable, "-I", os.path.join(os.path.dirname(HERE), "bench", "bench.py"), "--rows", a.rows, "--runs", a.runs],
                   capture_output=True, text=True, env=env)
lines = [l for l in p.stdout.splitlines() if l.startswith("|")]
if len(lines) < 3:
    sys.exit("bench.py failed: " + (p.stdout + p.stderr)[-400:])
names = [c.strip() for c in lines[0].strip("|").split("|")][3:]
rows = []
import re
for l in lines[2:]:
    m = re.match(r"^\| (\d+) \| (.+?) \| `(.*)` \| (.*) \|$", l)
    rows.append(dict(rows=int(m.group(1)), size=m.group(2), filter=m.group(3), ms=dict(zip(names, [x.strip() for x in m.group(4).split("|")]))))
commit = ""
if a.jx_repo:
    commit = subprocess.run(["git", "-C", a.jx_repo, "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
rec = dict(label=a.label, date=a.date or datetime.date.today().isoformat(), commit=commit, unit="median ms, whole process, Windows", timing=rows)
os.makedirs(a.results, exist_ok=True)
path = os.path.join(a.results, "%s-%s-timing.json" % (rec["date"], a.label))
json.dump(rec, open(path, "w", encoding="utf-8", newline="\n"), indent=1)
print("wrote", path, len(rows), "rows")
